function suppressHmrWebSocketErrorPlugin(): Plugin {
  return {
    name: 'suppress-hmr-ws-error',
    transform(code, id) {
      if (id.includes('vite/dist/client/client.mjs')) {
        return {
          code: code.replace(
            /reject\(\/\*\s*@__PURE__\s*\*\/\s*new Error\("WebSocket closed without opened\."\)\)/g,
            'resolve()'
          ),
          map: null,
        };
      }
      return null;
    },
  };
}

